// @ts-check
/**
 * Reads content/creators/<slug>.json (one file per creator page) and builds the small index the
 * sitemap, the footer and the game galleries use (creators-index.json).
 *
 * Shared by the Next.js pages (build time) and by scripts/creators-index.mjs, so both use the
 * same "live" rule. Server-only (reads files). Never import it from a client component.
 *
 * A creator page is "live" (indexed, in the sitemap, linked from indexed pages) when:
 *   - status is "published", AND
 *   - the written analysis exists (analysis is not null).
 * Everything else is still built, served with noindex.
 */

import fs from 'node:fs';
import path from 'node:path';

export const CREATORS_DIR = path.join('content', 'creators');
export const CREATORS_INDEX_PATH = path.join('src', 'components', 'v2', 'creators', 'creators-index.json');

/** @param {string} file */
export function isCreatorFile(file) {
  return file.endsWith('.json') && !file.startsWith('_');
}

/**
 * Every creator file, sorted by slug. Files that cannot be read or parsed are skipped with a warning
 * (an agent may be writing one at this moment); they never stop the build.
 * @param {string} [rootDir] app root (the folder that contains "content/")
 * @returns {Record<string, any>[]}
 */
export function readCreatorFiles(rootDir = process.cwd()) {
  const dir = path.join(rootDir, CREATORS_DIR);
  if (!fs.existsSync(dir)) return [];
  /** @type {Record<string, any>[]} */
  const out = [];
  for (const file of fs.readdirSync(dir).filter(isCreatorFile).sort()) {
    try {
      const data = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
      if (!data || typeof data.slug !== 'string' || !data.slug) {
        console.warn(`[creators] ${file}: no "slug", skipped`);
        continue;
      }
      out.push(data);
    } catch (e) {
      console.warn(`[creators] ${file}: cannot be read (${/** @type {Error} */ (e).message}), skipped`);
    }
  }
  return out;
}

/** @param {Record<string, any>} c */
export function isLive(c) {
  return c.status === 'published' && c.analysis != null;
}

/**
 * The index written to creators-index.json.
 * @param {Record<string, any>[]} creators
 */
export function computeCreatorsIndex(creators) {
  return {
    note: 'Generated by scripts/creators-index.mjs from content/creators. Do not edit by hand.',
    creators: creators.map((c) => ({
      slug: c.slug,
      name: c.name ?? c.slug,
      game: c.game ?? null,
      live: isLive(c),
      collectedAt: c.collectedAt ?? null,
      avatar: c.avatar ?? null,
      subscribersText: c.subscribersText ?? null,
    })),
  };
}

/** @param {string} [rootDir] */
export function readCreatorsIndexFile(rootDir = process.cwd()) {
  try {
    return JSON.parse(fs.readFileSync(path.join(rootDir, CREATORS_INDEX_PATH), 'utf8'));
  } catch {
    return null;
  }
}

/**
 * Stops the production build when creators-index.json no longer matches the creator files
 * (the sitemap would list the wrong pages). Fix: run `node scripts/creators-index.mjs`.
 * In development it only warns.
 */
export function assertCreatorsIndexFresh() {
  const expected = computeCreatorsIndex(readCreatorFiles());
  const actual = readCreatorsIndexFile();
  if (actual && JSON.stringify(expected.creators) === JSON.stringify(actual.creators)) return;
  const message =
    '[creators] The creators index is out of date: the creator files changed. ' +
    'Run "node scripts/creators-index.mjs" in blog-nextjs/ and commit ' +
    `${CREATORS_INDEX_PATH.split(path.sep).join('/')}.`;
  if (process.env.NODE_ENV === 'production') throw new Error(message);
  console.warn(message);
}
